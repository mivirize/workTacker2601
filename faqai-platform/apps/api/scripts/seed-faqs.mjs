const API = 'http://localhost:3001/api/v1';
const SITE_ID = 'bc0f3c96-bc30-4eda-bb6c-7e8182b5d136';

async function login() {
  const res = await fetch(`${API}/auth/login`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'e2e@faqai.test', password: 'E2ETest123' }),
  });
  const data = await res.json();
  return data.data.tokens.accessToken;
}

async function createFaq(token, question, answer, status = 'published') {
  const res = await fetch(`${API}/faqs`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json; charset=utf-8',
      Authorization: `Bearer ${token}`,
    },
    body: JSON.stringify({ siteId: SITE_ID, question, answer, status }),
  });
  const data = await res.json();
  if (!data.success) {
    console.error(`  FAILED: ${question.slice(0, 30)}`, data.error);
  } else {
    console.log(`  OK: ${question.slice(0, 40)}`);
  }
  return data;
}


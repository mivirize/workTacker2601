async function main() {
  console.log('=== G-DIRECT FAQ Seed ===');
  console.log(`Total: ${FAQS.length} FAQs to create\n`);

  const token = await login();
  console.log('Login OK\n');

  let created = 0;
  for (const faq of FAQS) {
    const result = await createFaq(token, faq.q, faq.a);
    if (result.success) created++;
  }

  console.log(`\nDone: ${created}/${FAQS.length} FAQs created`);
}

main().catch(console.error);
